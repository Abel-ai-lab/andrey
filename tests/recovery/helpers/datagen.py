def _linear_sem(seed: int, n_samples: int, weights: list[list[float]], noise: str) -> np.ndarray:
    """Linear structural equation model ``x_j = sum_i B[j, i] x_i + e_j``.

    ``weights`` is a strictly lower-triangular ``(d, d)`` coefficient matrix, so
    the recurrence fills columns in causal order ``0 -> 1 -> ... -> d-1``.
    ``noise`` selects ``"uniform"`` (non-Gaussian, for LiNGAM) or ``"gaussian"``.
    """
    rng = np.random.default_rng(seed)
    B = np.asarray(weights, dtype=np.float64)
    d = B.shape[0]
    e = _noise(rng, (n_samples, d), noise)
    X = np.zeros((n_samples, d), dtype=np.float64)
    for j in range(d):
        X[:, j] = e[:, j] + X @ B[j]
    return X


def _noise(rng: np.random.Generator, shape: tuple[int, int], noise: str) -> np.ndarray:
    """Draw an innovation array: ``"uniform"`` (non-Gaussian) or ``"gaussian"``."""
    if noise == "uniform":
        return rng.uniform(-1.0, 1.0, size=shape)
    if noise == "gaussian":
        return rng.standard_normal(size=shape)
    raise ValueError(f"unknown noise model: {noise!r}")


def _var_process(
    seed: int,
    n_samples: int,
    B0: list[list[float]],
    A1: list[list[float]],
    noise: str,
    burn_in: int,
) -> np.ndarray:
    """Stable VAR(1) with instantaneous LiNGAM mixing:
    ``x_t = B0 x_t + A1 x_{t-1} + e_t`` solved as
    ``x_t = (I - B0)^{-1} (A1 x_{t-1} + e_t)``.

    ``B0`` is acyclic (an instantaneous causal order), ``A1`` the
    lag-1 matrix; both are chosen so the reduced-form spectral radius is < 1. A
    ``burn_in`` prefix is discarded so the returned window is stationary.
    """
    rng = np.random.default_rng(seed)
    B0a = np.asarray(B0, dtype=np.float64)
    A1a = np.asarray(A1, dtype=np.float64)
    d = B0a.shape[0]
    total = n_samples + burn_in
    e = _noise(rng, (total, d), noise)
    ib_inv = np.linalg.inv(np.eye(d) - B0a)
    X = np.zeros((total, d), dtype=np.float64)
    X[0] = ib_inv @ e[0]
    for t in range(1, total):
        X[t] = ib_inv @ (A1a @ X[t - 1] + e[t])
    return X[burn_in:]


def _lagged_var(
    seed: int, n_samples: int, lags: list[list[list[float]]], noise: str, burn_in: int
) -> np.ndarray:
    """Stable VAR(p) with lagged effects only: ``x_t = A_1 x_{t-1} + ... + A_p x_{t-p} + e_t``.

    ``lags`` lists ``A_1 .. A_p``, each ``A_k[i, j]`` the effect of ``x_j(t-k)`` on ``x_i(t)``;
    there is no instantaneous mixing, so the lagged edges are exactly the nonzero entries. A
    ``burn_in`` prefix is discarded so the returned window is stationary.
    """
    rng = np.random.default_rng(seed)
    A = np.asarray(lags, dtype=np.float64)
    p, d = A.shape[0], A.shape[1]
    total = n_samples + burn_in
    e = _noise(rng, (total, d), noise)
    X = np.zeros((total, d), dtype=np.float64)
    for t in range(total):
        X[t] = e[t] + sum(A[k] @ X[t - k - 1] for k in range(min(p, t)))
    return X[burn_in:]


def _varma_process(
    seed: int,
    n_samples: int,
    B0: list[list[float]],
    A1: list[list[float]],
    M1: list[list[float]],
    noise: str,
    burn_in: int,
) -> np.ndarray:
    """Stable VARMA(1,1) with instantaneous mixing:
    ``x_t = B0 x_t + A1 x_{t-1} + e_t + M1 e_{t-1}`` solved as
    ``x_t = (I - B0)^{-1} (A1 x_{t-1} + e_t + M1 e_{t-1})``.

    ``A1`` (AR) and ``M1`` (MA) are small so the process is stationary and
    invertible; the ``burn_in`` prefix is discarded.
    """
    rng = np.random.default_rng(seed)
    B0a = np.asarray(B0, dtype=np.float64)
    A1a = np.asarray(A1, dtype=np.float64)
    M1a = np.asarray(M1, dtype=np.float64)
    d = B0a.shape[0]
    total = n_samples + burn_in
    e = _noise(rng, (total, d), noise)
    ib_inv = np.linalg.inv(np.eye(d) - B0a)
    X = np.zeros((total, d), dtype=np.float64)
    X[0] = ib_inv @ e[0]
    for t in range(1, total):
        X[t] = ib_inv @ (A1a @ X[t - 1] + e[t] + M1a @ e[t - 1])
    return X[burn_in:]


def _panel_process(
    seed: int,
    n_samples: int,
    times: int,
    B0: list[list[float]],
    A1: list[list[float]],
    noise: str,
) -> list[np.ndarray]:
    """Panel of ``n_samples`` units at ``times`` time points with instantaneous mixing:
    ``x_t = B0 x_t + A1 x_{t-1} + e_t``, ``x_0 = B0 x_0 + e_0``, one ``(n_samples, d)`` matrix per
    time point. ``B0`` is strictly lower-triangular, so the instantaneous causal order is
    ``0 -> 1 -> ... -> d-1``.
    """
    rng = np.random.default_rng(seed)
    B0a = np.asarray(B0, dtype=np.float64)
    A1a = np.asarray(A1, dtype=np.float64)
    ib_inv = np.linalg.inv(np.eye(B0a.shape[0]) - B0a)
    x = _noise(rng, (n_samples, B0a.shape[0]), noise) @ ib_inv.T
    panel = [x]
    for _ in range(1, times):
        x = (x @ A1a.T + _noise(rng, x.shape, noise)) @ ib_inv.T
        panel.append(x)
    return panel


def _anm_pair(seed: int, n_samples: int, x_range: float, noise_scale: float) -> np.ndarray:
    """Nonlinear additive-noise pair ``x -> y`` with ``y = x**3 + n``.

    ``x`` is a non-Gaussian (uniform) cause and ``n`` an independent uniform
    noise; the cubic makes the direction identifiable for ANM/PNL. Returns an
    ``(n_samples, 2)`` matrix with column 0 = cause, column 1 = effect.
    """
    rng = np.random.default_rng(seed)
    x = rng.uniform(-x_range, x_range, size=n_samples)
    n = rng.uniform(-noise_scale, noise_scale, size=n_samples)
    # A multiplication chain, not ``x**3``: each multiply is exactly rounded on every machine,
    # while numpy dispatches ``power`` to a SIMD kernel chosen from the host's CPU features, so the
    # cube's last bits -- and with them this case's input hash -- would vary by runner.
    y = x * x * x + n
    return np.column_stack([x, y]).astype(np.float64)


def _confounded_sem(
    seed: int,
    n_samples: int,
    weights: list[list[float]],
    noise: str,
    observed: list[int],
) -> np.ndarray:
    """Linear non-Gaussian SEM over all variables, returning only ``observed``
    columns so the dropped variables act as unobserved confounders.

    ``weights`` is strictly lower-triangular over the full order (latents first);
    projecting away the latent columns leaves confounded observed pairs for
    RCD / CAM-UV / BottomUpParceLiNGAM to recover.
    """
    X_full = _linear_sem(seed=seed, n_samples=n_samples, weights=weights, noise=noise)
    return X_full[:, list(observed)]


def _confounded_anm(
    seed: int, n_samples: int, noise_scale: float, observed: list[int]
) -> np.ndarray:
    """Nonlinear additive-noise SEM over ``h, x0, x1, x2, x3``, returning only ``observed`` columns.

    The hidden ``h`` is uniform on ``(-1, 1)`` and drives ``x0 = sin(3h) + n`` and
    ``x1 = cos(3h) + n``: an odd and an even function of ``h``, so neither variable is an additive
    function of the other. Then ``x2 = x1**2 + n`` and ``x3 = tanh(2 x0) + n``. Each ``n`` is an
    independent uniform draw on ``(-noise_scale, noise_scale)``. Column indices in ``observed``
    count ``h`` as column 0.

    ``sin``, ``cos``, and ``tanh`` use numpy kernels chosen from the host's CPU features, so the
    last bits of the output, and its input hash, can differ by machine; no baseline pins this case.
    """
    rng = np.random.default_rng(seed)
    h = rng.uniform(-1.0, 1.0, size=n_samples)
    n = rng.uniform(-noise_scale, noise_scale, size=(n_samples, 4))
    x0 = np.sin(3.0 * h) + n[:, 0]
    x1 = np.cos(3.0 * h) + n[:, 1]
    x2 = x1 * x1 + n[:, 2]
    x3 = np.tanh(2.0 * x0) + n[:, 3]
    return np.column_stack([h, x0, x1, x2, x3])[:, list(observed)]


