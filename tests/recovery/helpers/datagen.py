def generate(case_id: str, *, replicate: int = 0) -> np.ndarray:
    """Return the input matrix for ``case_id`` (reproducible from its seed).

    Dispatches on the case's ``"model"`` key (default ``"linear_sem"``). ``replicate`` shifts the
    seed to draw another sample of the same SEM; replicate 0 is the pinned input.
    """
    spec = CASES[case_id]
    seed = spec["seed"] + replicate
    model = spec.get("model", "linear_sem")
    if model == "linear_sem":
        return _linear_sem(
            seed=seed,
            n_samples=spec["n_samples"],
            weights=spec["weights"],
            noise=spec["noise"],
        )
    if model == "var":
        X = _var_process(
            seed=seed,
            n_samples=spec["n_samples"],
            B0=spec["B0"],
            A1=spec["A1"],
            noise=spec["noise"],
            burn_in=spec["burn_in"],
        )
        return np.ascontiguousarray(X[:, spec["observed"]]) if "observed" in spec else X
    if model == "lagged_var":
        return _lagged_var(
            seed=seed,
            n_samples=spec["n_samples"],
            lags=spec["lags"],
            noise=spec["noise"],
            burn_in=spec["burn_in"],
        )
    if model == "varma":
        return _varma_process(
            seed=seed,
            n_samples=spec["n_samples"],
            B0=spec["B0"],
            A1=spec["A1"],
            M1=spec["M1"],
            noise=spec["noise"],
            burn_in=spec["burn_in"],
        )
    if model == "anm":
        return _anm_pair(
            seed=seed,
            n_samples=spec["n_samples"],
            x_range=spec["x_range"],
            noise_scale=spec["noise_scale"],
        )
    if model == "confounded":
        return _confounded_sem(
            seed=seed,
            n_samples=spec["n_samples"],
            weights=spec["weights"],
            noise=spec["noise"],
            observed=spec["observed"],
        )
    if model == "confounded_anm":
        return _confounded_anm(
            seed=seed,
            n_samples=spec["n_samples"],
            noise_scale=spec["noise_scale"],
            observed=spec["observed"],
        )
    raise ValueError(f"unknown case model: {model!r}")


def planted_structure(case_id: str) -> tuple[set[tuple[int, int]], set[tuple[int, int]]]:
    """Return ``(edges, confounded_pairs)`` of a hidden-confounder case, over its observed columns.

    ``edges`` holds ``(i, j)`` for each direct cause ``i -> j`` between observed columns, and
    ``confounded_pairs`` each ``(i, j)``, ``i < j``, of non-adjacent observed columns with a shared
    hidden parent. Indices count positions in the generated matrix. A linear case derives both from
    its weights; a nonlinear case lists them.
    """
    spec = CASES[case_id]
    if spec["model"] == "confounded_anm":
        return {tuple(e) for e in spec["edges"]}, {tuple(p) for p in spec["confounded_pairs"]}
    B = np.asarray(spec["weights"])  # B[j, i] != 0 is the edge i -> j over the full order
    observed = list(spec["observed"])
    hidden = [c for c in range(B.shape[0]) if c not in observed]
    position = {column: k for k, column in enumerate(observed)}
    edges = {(position[i], position[j]) for i in observed for j in observed if B[j, i] != 0}
    confounded = {
        (position[a], position[b])
        for a, b in combinations(observed, 2)
        if B[a, b] == 0 and B[b, a] == 0 and any(B[a, h] != 0 and B[b, h] != 0 for h in hidden)
    }
    return edges, confounded


def generate_groups(case_id: str) -> list[np.ndarray]:
    """Return the list of input matrices for a multi-group ``case_id`` (one per group)."""
    spec = GROUP_CASES[case_id]
    if spec.get("model") == "panel":
        return _panel_process(
            seed=spec["seed"],
            n_samples=spec["n_samples"],
            times=spec["times"],
            B0=spec["B0"],
            A1=spec["A1"],
            noise=spec["noise"],
        )
    return [
        _linear_sem(
            seed=group["seed"],
            n_samples=spec["n_samples"],
            weights=group["weights"],
            noise=spec["noise"],
        )
        for group in spec["groups"]
    ]


def domain_index(case_id: str, *, n_domains: int = 2) -> np.ndarray:
    """A deterministic ``(n_samples, 1)`` domain/context index for CDNOD over ``case_id``.

    Splits the samples into ``n_domains`` contiguous equal blocks labeled ``0..n_domains-1`` -- a
    fixed, reproducible surrogate for a nonstationary index. This case checks the output
    contract; domain-shift recovery has separate tests.
    """
    n = CASES[case_id]["n_samples"]
    c = np.zeros((n, 1), dtype=np.float64)
    block = n // n_domains
    for k in range(1, n_domains):
        c[k * block :, 0] = float(k)
    return c


def input_sha256(case_id: str) -> str:
    """SHA-256 of the case's input matrix (or all group matrices, in order, for a group case).

    Bytes are pinned little-endian (``<f8``) so the digest is identical across
    architectures (byte-identical to native float64 on little-endian hosts).
    """
    digest = hashlib.sha256()
    matrices = generate_groups(case_id) if case_id in GROUP_CASES else [generate(case_id)]
    for X in matrices:
        digest.update(np.ascontiguousarray(X, dtype="<f8").tobytes())
    return digest.hexdigest()
