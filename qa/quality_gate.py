def intervention_draws(d: int, n: int) -> tuple[Draw, ...]:
    """The samples beside their 0/1 intervention matrix (:func:`stack`), with the interventional
    essential graph of the true DAG under the rows' targets."""
    out = []
    for seed in SEEDS:
        x, interventions, dag = gies_cpu.sample(
            d, seed, rows_per_variable=n // d, target_share=TARGET_SHARE
        )
        truth = gies_cpu.essential_graph(dag, interventions)
        out.append(Draw(stack(x, interventions), GraphStructure.from_numpy(truth, kind="cpdag")))
    return tuple(out)


def noise_intervention_draws(cell: str) -> tuple[Draw, ...]:
    """The samples with each row's environment as the last column, and the interventional essential
    graph of the true DAG under the true targets."""
    spec = gnies_cpu.BY_NAME[cell]
    out = []
    for seed in SEEDS:
        ds = gnies_cpu.draw(spec, seed)
        truth = gnies_cpu.essential_graph(ds.dag, singleton_cut(ds.true_targets, spec.d))
        x = np.column_stack([ds.X, ds.env])
        out.append(Draw(x, GraphStructure.from_numpy(truth, kind="cpdag")))
    return tuple(out)


def known_target_stack(x: np.ndarray, env: np.ndarray, targets: list[list[int]]) -> np.ndarray:
    """The samples, each row's environment, and a 0/1 matrix marking, in each row of a setting, its
    targets: the benchmark driver's ``known`` matrix."""
    known = np.zeros(x.shape)
    for k, setting in enumerate(targets, start=1):
        known[np.ix_(env == k, setting)] = 1
    return np.column_stack([x, env, known])


def known_target_unstack(x: np.ndarray) -> tuple[np.ndarray, np.ndarray, list[list[int]]]:
    """The samples, the environments, and each setting's targets of :func:`known_target_stack`."""
    p = (x.shape[1] - 1) // 2
    env = x[:, p].astype(int)
    known = x[:, p + 1 :]
    targets = [np.flatnonzero(known[env == k][0]).tolist() for k in range(1, env.max() + 1)]
    return x[:, :p], env, targets


def known_target_draws(cell: str) -> tuple[Draw, ...]:
    """The stacked samples (:func:`known_target_stack`) with the interventional essential graph of
    the true DAG under the targets."""
    spec = igsp_cpu.cell_named(cell)
    out = []
    for seed in SEEDS:
        x, env, truth = igsp_cpu.dataset(spec, seed)
        graph = igsp_cpu.essential(np.asarray(truth["dag"]), truth["effective"])
        out.append(
            Draw(
                known_target_stack(x, env, truth["given"]),
                GraphStructure.from_numpy(graph, kind="cpdag"),
            )
        )
    return tuple(out)


def model_draws(regime: str, d: int, n: int) -> tuple[Draw, ...]:
    """One draw per seed of a :mod:`andrey_bench.regime_models` regime, with its truth: CD-NOD's
    identifiable CPDAG, the groups' block-diagonal DAG, or the measurement DAG, latents last."""
    model, noise = MODEL_REGIMES[regime]
    latents = regime_models.latents_for(model, d)
    types = None
    if latents:
        types = np.full(d, OBSERVED, dtype=np.int8)
        types[d - latents :] = LATENT
    out = []
    for seed in SEEDS:
        # Mean degree 2, as the published keys; the measurement model takes no density.
        x, marks, kind, _ = regime_models.sample(
            model, d=d, n=n, seed=seed, density=2.0, noise=noise
        )
        out.append(Draw(x, GraphStructure.from_numpy(marks, kind=kind, node_types=types)))
    return tuple(out)


