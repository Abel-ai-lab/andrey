def context_columns(x: np.ndarray) -> dict[str, list[int]]:
    """The observed time and space contexts of a J-PCMCI+ draw (:func:`context_draws`)."""
    contexts = list(range(CONTEXT_SYSTEM, x.shape[-1]))
