#: What an estimate is scored against: the truth's CPDAG, its DAG, the PAG of its observed nodes,
#: its latent projection (:func:`projection`), or, as ``essential``, the graph the draw makes
#: identifiable, recorded with it: the interventional essential graph, or the CPDAG in which the
#: domain index orients the edges it reaches. ``clusters`` counts the latents missed
#: (:func:`latents_missed`). A time-series estimate is scored in its published summary's unit
#: (:func:`series_error`).
Target = Literal[
    "cpdag",
    "dag",
    "pag",
    "projection",
    "essential",
    "clusters",
    "lagged",
    "window",
    "cross_links",
    "lagged_edges",
]
SERIES_TARGETS = ("lagged", "window", "cross_links", "lagged_edges")


@dataclass(frozen=True)
class Method:
    fit: Callable[[Any], Any]
    target: Target
    datasets: tuple[str, ...]


def _sizes(regime: str) -> tuple[str, ...]:
    return tuple(f"{regime}_d{d}" for d, _ in sizes(regime))


# A method applies where its assumptions hold. PC and the score searches (GES, XGES, HC, Tabu, BOSS,
# GRaSP, exact search, CALM) assume no hidden variables, FCI and GFCI allow them, and the LiNGAM
# methods need non-Gaussian noise. Sachs is measured data that fits each only approximately. RCD and
# BottomUpParceLiNGAM run on their benchmark regime only: on ASIA's 1,000 rows RCD marks most pairs
# <-> and scores worse than the empty graph, and on Sachs BottomUpParceLiNGAM does. ANM and PNL take
# one pair of variables, so each runs on its benchmark's pairs only. GIES, CD-NOD,
# MultiGroupDirectLiNGAM, and GIN need what only their regimes have: interventions, domains,
# groups, or latents measured by indicators.
CPDAG_DATA = (*_sizes("linear_gauss_er"), "asia_gauss", "sachs")
SMALL_DATA = (*(f"linear_gauss_er_d{d}" for d, _ in SMALL_SIZES), "asia_gauss", "sachs")
CALM_DATA = (SMALL_DATA[0], "asia_gauss")
PAG_DATA = (*_sizes("latent_gauss_er"), "asia_gauss", "sachs")
LINGAM_DATA = (*_sizes("lingam_sf"), "asia_lingam", "sachs")
CONFOUNDED_DATA = _sizes("latent_lingam_er")
INTERVENTION_DATA = tuple(f"interventional_gauss_er_d{d}" for d, _ in INTERVENTION_SIZES)


def _models(regime: str) -> tuple[str, ...]:
    return tuple(f"{regime}_d{d}" for d, _ in MODEL_SIZES[regime])


def _series(regime: str) -> tuple[str, ...]:
    return tuple(f"{regime}_d{d}_n{n}" for d, n in SERIES_SIZES[regime])


def _adapted(adapter: Any) -> Callable[[Any], Any]:
    """The benchmark adapter's fit with the published settings, as the harness scores it."""
    return lambda x: adapter.to_structure(adapter.fit(x, adapter.params()))


def _granger(x: np.ndarray) -> np.ndarray:
    """The lagged edges of ``andrey.granger`` with the published settings, as ``(lag, cause,
    effect)``."""
    out = andrey.granger(x, tau_max=GRANGER_LAGS)
    return np.stack([np.asarray(w) != 0 for w in out.structure.lag_weights])


