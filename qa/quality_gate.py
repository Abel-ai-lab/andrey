def context_draws(cell: str) -> tuple[Draw, ...]:
    """The datasets of a J-PCMCI+ cell, ``(datasets, steps, columns)``: the system variables, then
    the observed time contexts, then the observed space contexts, as many of each kind; and the
    window graph of the system variables over lags 0 to 2. A seed whose draw breaks Assumption 3 is
    skipped and the next one taken, as the driver's claimed rows leave it out."""
    out: list[Draw] = []
    seed = 0
    while len(out) < len(SEEDS):
        ds = jpcmciplus_cpu.draw(jpcmciplus_cpu.CELLS[cell], seed)
        seed += 1
        if not ds.draw.breaks_assumption_3:
            out.append(Draw(ds.draw.datasets, ds.truth))
    return tuple(out)


def parents_of(graph: Any, node: int) -> set[int]:
    """Return the nodes with an edge into ``node`` in ``graph``, a structure or an output."""
    marks = getattr(graph, "structure", graph).to_numpy()
    return {int(j) for j in np.flatnonzero((marks[:, node] == TAIL) & (marks[node] == ARROW))}


def invariance_draws(d: int, n: int) -> tuple[Draw, ...]:
    """One draw per seed of linear-Gaussian data in environments, with its true DAG.

    The seed draws the graph, standardized as in :data:`REGIMES`, and the target, a variable with
    parents. The environments are observation and :data:`INVARIANCE_DO` on each other variable,
    ``n`` rows each. The data are each row's environment, then the variables with the target last,
    the layout :func:`icp_fit` and the ``parents`` score read.
    """
    out = []
    for seed in SEEDS:
        scm = data.SCM(
            graph=data.graphs.erdos_renyi(d, avg_degree=2.0),
            functional=data.functional.linear(),
            noise=data.noise.gaussian(),
        )
        graph = scm.sample(n=2, seed=seed).graph  # the same graph and columns as the draw below
        rng = np.random.default_rng([seed, d])
        target = int(rng.choice([j for j in range(d) if parents_of(graph, j)]))
        others = [j for j in range(d) if j != target]
        envs = [{}, *({j: hard(INVARIANCE_DO[0], sd=INVARIANCE_DO[1])} for j in others)]
        ds = scm.sample(n=n, seed=seed, envs=envs)
        order = [*others, target]
        marks = ds.graph.to_numpy()[np.ix_(order, order)]
        x = np.column_stack([np.asarray(ds.env), ds.data[:, order]])
        out.append(Draw(x, GraphStructure.from_numpy(marks, kind="dag")))
    return tuple(out)


def asia_draws(noise: str) -> tuple[Draw, ...]:
    scm = data.SCM(
        graph=data.graphs.FixedDAG(nodes=ASIA_NODES, arcs=ASIA_ARCS),
        functional=data.functional.linear(),
        noise=getattr(data.noise, noise)(),
    )
    samples = (scm.sample(n=ASIA_N, seed=s, scale="standardize") for s in SEEDS)
    return tuple(Draw(ds.data, ds.graph) for ds in samples)


def unknown_target_stack(x: np.ndarray, env: np.ndarray, given: list[list[int]]) -> np.ndarray:
    """The samples, each row's environment, and a 0/1 matrix marking, in each row of a setting, the
    targets the fit is given: the benchmark driver's ``known`` matrix."""
    known = np.zeros(x.shape)
    for k, targets in enumerate(given, start=1):
        known[np.ix_(env == k, targets)] = 1
    return np.column_stack([x, env, known])


def unknown_target_unstack(x: np.ndarray) -> tuple[np.ndarray, np.ndarray, list[list[int]]]:
    """The samples, the environments, and each setting's given targets of
    :func:`unknown_target_stack`."""
    p = (x.shape[1] - 1) // 2
    env = x[:, p].astype(int)
    known = x[:, p + 1 :]
    given = [np.flatnonzero(known[env == k][0]).tolist() for k in range(1, env.max() + 1)]
    return x[:, :p], env, given


def unknown_target_draws(cell: str) -> tuple[Draw, ...]:
    """The stacked samples (:func:`unknown_target_stack`), the interventional essential graph of the
    true DAG under the true targets, and the true targets."""
    spec = ut_igsp_cpu.cell_named(cell)
    out = []
    for seed in SEEDS:
        x, env, truth = ut_igsp_cpu.dataset(spec, seed)
        graph = ut_igsp_cpu.essential(np.asarray(truth["dag"]), truth["true"])
        out.append(
            Draw(
                unknown_target_stack(x, env, truth["given"]),
                GraphStructure.from_numpy(graph, kind="cpdag"),
                targets=truth["true"],
            )
        )
    return tuple(out)


