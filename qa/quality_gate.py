@dataclass(frozen=True)
class Draw:
    """Samples and their true graph. Hidden nodes come last and have no column.

    A time series's truth is the benchmark harness's: lag links, a window graph, a coefficient
    stack, or the lagged edges as a ``(lag, cause, effect)`` boolean stack.
    """

    data: np.ndarray
    truth: Any


#: The published regimes as ``andrey.data.sample_scm`` arguments: mean degree 2 and standardized
#: columns, with hidden nodes in the ``latent_*`` regimes (:data:`HIDDEN`).
REGIMES: dict[str, dict[str, str]] = {
    "linear_gauss_er": {"graph": "erdos_renyi", "noise": "gaussian"},
    "latent_gauss_er": {"graph": "erdos_renyi", "noise": "gaussian"},
    "lingam_sf": {"graph": "scale_free", "noise": "uniform"},
    "latent_lingam_er": {"graph": "erdos_renyi", "noise": "uniform"},
}

#: One node in this many is hidden, at least one.
HIDDEN: dict[str, int] = {"latent_gauss_er": 10, "latent_lingam_er": 5}

#: ``(d, n)`` for a regime. The benchmarks use ``n = 10d``, where ICA-LiNGAM scores worse than the
#: empty graph. At ``n = 50d`` every method's correct output beats it, so the check has power.
SIZES: tuple[tuple[int, int], ...] = ((20, 1000), (50, 2500))
#: ``latent_lingam_er`` keeps its benchmark's 2,000 rows; ``d`` counts the hidden nodes. At
#: ``d = 20`` BottomUpParceLiNGAM's median SHD is no lower than the empty graph's (37.5 and 36 over
#: ten seeds), so the check would have no power there.
REGIME_SIZES: dict[str, tuple[tuple[int, int], ...]] = {
    "latent_lingam_er": ((10, 2000), (15, 2000)),
}
#: Smaller ``linear_gauss_er`` draws, at ``n = 50d``, for exact search, whose run time at least
#: doubles with each variable, and CALM, whose optimizer step's cost grows with the cube of the
#: variable count, so it runs on the smaller one and ASIA only.
SMALL_SIZES: tuple[tuple[int, int], ...] = ((10, 500), (15, 750))
SEEDS = range(10)
ASIA_N = 1000

#: ASIA (Lauritzen and Spiegelhalter, 1988): 8 variables and 8 arcs, the same as
#: ``andrey.data.load_dataset("asia").graph`` (a test checks). This arc order fixes each seed's
#: weights, and so the baselines.
ASIA_NODES = ("asia", "tub", "smoke", "lung", "bronc", "either", "xray", "dysp")
ASIA_ARCS = (
    ("asia", "tub"),
    ("smoke", "lung"),
    ("smoke", "bronc"),
    ("tub", "either"),
    ("lung", "either"),
    ("either", "xray"),
    ("either", "dysp"),
    ("bronc", "dysp"),
)


#: The published cause-effect pair regimes as ``andrey.data.sample_scm`` arguments: two
#: standardized nodes at mean degree 1, so every pair has one edge, in a direction the seed draws.
PAIRS: dict[str, dict[str, str]] = {
    "anm_pair": {"functional": "additive_noise", "noise": "gaussian"},
    "pnl_pair": {"functional": "post_nonlinear", "noise": "laplace"},
}
#: Rows per pair. The empty graph's SHD on a pair is 1, so a method passes only when its median SHD
#: is 0: it names the true direction on most draws, as ANM and PNL do from 1,000 rows.
PAIR_N = 1000

#: ``(d, n)`` of GIES's published regime, ``interventional_gauss_er``, at ``n = 50d``, drawn by its
#: benchmark driver: a share :data:`TARGET_SHARE` of the variables, rounded, are intervention
#: targets, and the rows split evenly between no intervention and each target.
INTERVENTION_SIZES: tuple[tuple[int, int], ...] = ((20, 1000), (50, 2500))
TARGET_SHARE = 0.4

#: The published regimes that :mod:`andrey_bench.regime_models` draws, as its model and noise, and
#: the ``(d, n)`` the gate draws each at: two published sizes, with the published rows. CD-NOD's
#: rows come from four domains, MultiGroupDirectLiNGAM's from three groups side by side, and in
#: ``latent_measurement``, ``d`` counts the latents and their three indicators each. GIN's number
#: of tests grows combinatorially with the indicator count, so it runs at the two smaller sizes.
MODEL_REGIMES: dict[str, tuple[str, str]] = {
    "domain_shift_er": ("domain_shift", "gaussian"),
    "multi_group_er": ("multi_group", "uniform"),
    "latent_measurement": ("measurement", "uniform"),
}
MODEL_SIZES: dict[str, tuple[tuple[int, int], ...]] = {
    "domain_shift_er": ((20, 2000), (50, 2000)),
    "multi_group_er": ((10, 1000), (20, 1000)),
    "latent_measurement": ((8, 1000), (12, 1000)),
}


def sizes(regime: str) -> tuple[tuple[int, int], ...]:
    """Return the ``(d, n)`` pairs the gate draws ``regime`` at."""
    return REGIME_SIZES.get(regime, SIZES)


def regime_kwargs(regime: str, d: int, n: int, seed: int) -> dict[str, Any]:
    """Return the ``andrey.data.sample_scm`` arguments for one draw of ``regime``."""
    kwargs: dict[str, Any] = {
        **REGIMES[regime],
        "functional": "linear",
        "d": d,
        "n": n,
        "seed": seed,
        "scale": "standardize",
        "density": 2.0,
        "shuffle": True,
    }
    if regime in HIDDEN:
        kwargs["latents"] = max(1, d // HIDDEN[regime])
    return kwargs


def pair_kwargs(regime: str, n: int, seed: int) -> dict[str, Any]:
    """Return the ``andrey.data.sample_scm`` arguments for one draw of the pair ``regime``."""
    return {
        "graph": "erdos_renyi",
        **PAIRS[regime],
        "d": 2,
        "n": n,
        "seed": seed,
        "scale": "standardize",
        "density": 1.0,
        "shuffle": True,
    }


def arc_indices(
    nodes: tuple[str, ...], arcs: tuple[tuple[str, str], ...]
) -> tuple[np.ndarray, np.ndarray]:
    """Return the parent and child index of each arc."""
    index = {name: i for i, name in enumerate(nodes)}
    return np.array([index[a] for a, _ in arcs]), np.array([index[b] for _, b in arcs])


def regime_draws(regime: str, d: int, n: int) -> tuple[Draw, ...]:
    samples = (data.sample_scm(**regime_kwargs(regime, d, n, s)) for s in SEEDS)
    return tuple(Draw(ds.data, ds.graph) for ds in samples)


def pair_draws(regime: str, n: int) -> tuple[Draw, ...]:
    samples = (data.sample_scm(**pair_kwargs(regime, n, s)) for s in SEEDS)
    return tuple(Draw(ds.data, ds.graph) for ds in samples)


def intervention_draws(d: int, n: int) -> tuple[Draw, ...]:
    """The samples beside their 0/1 intervention matrix (:func:`stack`), with the interventional
    essential graph of the true DAG under the rows' targets."""
    out = []
    for seed in SEEDS:
        x, interventions, dag = gies_cpu.sample(
            d, seed, rows_per_variable=n // d, target_share=TARGET_SHARE
        )
        truth = gies_cpu.essential_graph(dag, interventions)
        out.append(Draw(stack(x, interventions), GraphStructure.from_numpy(truth, kind="cpdag")))
    return tuple(out)


def model_draws(regime: str, d: int, n: int) -> tuple[Draw, ...]:
    """One draw per seed of a :mod:`andrey_bench.regime_models` regime, with its truth: CD-NOD's
    identifiable CPDAG, the groups' block-diagonal DAG, or the measurement DAG, latents last."""
    model, noise = MODEL_REGIMES[regime]
    latents = regime_models.latents_for(model, d)
    types = None
    if latents:
        types = np.full(d, OBSERVED, dtype=np.int8)
        types[d - latents :] = LATENT
    out = []
    for seed in SEEDS:
        # Mean degree 2, as the published keys; the measurement model takes no density.
        x, marks, kind, _ = regime_models.sample(
            model, d=d, n=n, seed=seed, density=2.0, noise=noise
        )
        out.append(Draw(x, GraphStructure.from_numpy(marks, kind=kind, node_types=types)))
    return tuple(out)


def asia_draws(noise: str) -> tuple[Draw, ...]:
    scm = data.SCM(
        graph=data.graphs.FixedDAG(nodes=ASIA_NODES, arcs=ASIA_ARCS),
        functional=data.functional.linear(),
        noise=getattr(data.noise, noise)(),
    )
    samples = (scm.sample(n=ASIA_N, seed=s, scale="standardize") for s in SEEDS)
    return tuple(Draw(ds.data, ds.graph) for ds in samples)


#: The published time-series regimes and the benchmark harness's model of each; a test checks the
#: names against the harness's regime table.
SERIES_MODELS: dict[str, str] = {
    "pcmci_paper": "pcmci2019",
    "pcmciplus_paper": "pcmciplus2020",
    "lpcmci_paper": "lpcmci2020",
    "varma_lingam_paper": "varma2010",
}
#: ``(d, n)``, the variables and time steps, of each time-series regime the gate draws: sizes of the
#: published summary at which the method's median error is below the empty graph's on most series.
#: PCMCI's is only at ``d = 10``; from ``d = 20`` its median error is near or above the empty
#: graph's. VARMA-LiNGAM's fit takes seconds, so it runs at the two smaller sizes.
SERIES_SIZES: dict[str, tuple[tuple[int, int], ...]] = {
    "pcmci_paper": ((10, 500), (10, 1000)),
    "pcmciplus_paper": ((10, 500), (20, 1000)),
    "lpcmci_paper": ((5, 500), (10, 1000)),
    "varma_lingam_paper": ((3, 300), (5, 300)),
}
#: ``(d, n, m)`` of the longitudinal LiNGAM panel: variables, time points, and units.
PANEL_MODEL = "panel2013"
PANEL_SIZES: tuple[tuple[int, int, int], ...] = ((3, 20, 200), (5, 20, 500))
#: The Granger regime ``var2_lagged``: lags of the true process, and the expected number of other
#: variables entering each lag of a variable. A test checks the draws against its benchmark driver.
GRANGER_LAGS = 2
GRANGER_LAG_DEGREE = 2.0
#: ``(d, n)`` of the Granger draws. At the published 1,000 steps the median error is above the
#: empty graph's at every published ``d``, so the check would have no power there; at ``d = 5`` it
#: is below.
GRANGER_SIZES: tuple[tuple[int, int], ...] = ((5, 1000), (5, 2000))


def series_draws(regime: str, d: int, n: int) -> tuple[Draw, ...]:
    """One series per seed of a paper regime, with its truth as the benchmark harness scores it."""
    model = SERIES_MODELS[regime]
    out = []
    for seed in SEEDS:
        if model in lingam_models.MODELS:
            series, stack, _ = lingam_models.sample_varma(model, d, n, seed)
            out.append(Draw(series, CoefficientStack(stack, kind="varma")))
            continue
        series, window = temporal_models.sample(model, d, n, seed)
        if temporal_models.MODELS[model].same_step:
            latents = temporal_models.hidden_count(model, d)
            truth = WindowGraph(window, lag0="dag", latents=latents)
        else:  # lagged links only, as ``(lag, cause, effect)`` links over lags 1..L
            truth = temporal_from_links(window[1:] != 0)
        out.append(Draw(series, truth))
    return tuple(out)


def panel_draws(d: int, n: int, m: int) -> tuple[Draw, ...]:
    """One panel of ``m`` units at ``n`` time points per seed, shaped ``(n, m, d)``."""
    samples = (lingam_models.sample_panel(PANEL_MODEL, d, n, m, s) for s in SEEDS)
    return tuple(Draw(panel, CoefficientStack(stack, kind="panel")) for panel, stack in samples)


def granger_draws(d: int, n: int) -> tuple[Draw, ...]:
    """A z-scored VAR(2) series per seed with no same-step links, and its lagged edges."""
    out = []
    for seed in SEEDS:
        scm = data.SCM(
            graph=data.graphs.erdos_renyi(d, avg_degree=0.0),
            functional=data.functional.var(
                n_lags=GRANGER_LAGS, lag_density=min(1.0, GRANGER_LAG_DEGREE / (d - 1))
            ),
            noise=data.noise.gaussian(),
        )
        ds = scm.sample(n=n, seed=seed)
        x = np.asarray(ds.data, dtype=np.float64)
        weights = np.asarray(ds.graph.lag_weights)  # (1 + lags, cause, effect), lag 0 first
        out.append(Draw((x - x.mean(axis=0)) / x.std(axis=0), weights[1:] != 0))
    return tuple(out)


def sachs_draws() -> tuple[Draw, ...]:
    """The Sachs observational rows and consensus network, downloaded once and cached."""
    sachs = data.load_dataset("sachs", as_frame=False)
    parents, children = arc_indices(SACHS_NODES, SACHS_ARCS)
    return (Draw(sachs.data, data.graphs.dag_truth(parents, children, len(SACHS_NODES))),)


