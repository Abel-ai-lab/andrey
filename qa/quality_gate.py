def projection(truth: GraphStructure) -> GraphStructure:
    """Return the latent projection of a DAG ``truth`` over its observed nodes, as a ``pag``.

    Observed ``i -> j`` when a directed path runs from ``i`` to ``j`` with every node between them
    hidden, a direct edge included. Observed ``i <-> j`` when one hidden node reaches both through
    hidden nodes only; it replaces ``i -> j`` on a pair that has both. These are the edges and the
    confounded pairs the published summary scores RCD and BottomUpParceLiNGAM on.
    """
    marks = truth.to_numpy()
    child = (marks == TAIL) & (marks.T == ARROW)  # child[i, j]: i -> j
    types = truth.node_types
    hidden = np.zeros(len(marks), dtype=bool) if types is None else np.asarray(types) == LATENT
    edges, pairs = [], []
    for source in range(len(marks)):
        seen, stack, reached = {source}, [source], set()
        while stack:
            for node in map(int, np.flatnonzero(child[stack.pop()])):
                if not hidden[node]:
                    reached.add(node)
                elif node not in seen:
                    seen.add(node)
                    stack.append(node)
        if hidden[source]:
            pairs += combinations(sorted(reached), 2)
        else:
            edges += [(source, node) for node in reached]
    n_observed = int(np.count_nonzero(~hidden))  # observed nodes come first
    out = np.zeros((n_observed, n_observed), dtype=np.int8)
    for i, j in edges:
        out[i, j], out[j, i] = TAIL, ARROW
    for i, j in pairs:
        out[i, j] = out[j, i] = ARROW
    return GraphStructure.from_numpy(out, kind="pag")


def directed(graph: Any) -> set[tuple[int, int]]:
    """Return the directed edges ``(i, j)``, ``i -> j``, of ``graph``, a structure or an output."""
    marks = getattr(graph, "structure", graph).to_numpy()
    return set(zip(*map(np.ndarray.tolist, np.nonzero((marks == TAIL) & (marks.T == ARROW)))))


def direct(truth: GraphStructure) -> GraphStructure:
    """Return the DAG over the observed nodes of ``truth`` with the edges CAM-UV can identify as
    direct: those between two observed nodes that no hidden causal or backdoor path joins
    (``andrey_bench.scoring.direct_edges``), the truth of its published direct-edge errors."""
    n_observed = truth.n_nodes - int(np.count_nonzero(np.asarray(truth.node_types) == LATENT))
    out = np.zeros((n_observed, n_observed), dtype=np.int8)
    for i, j in scoring.direct_edges(truth):
        out[i, j], out[j, i] = TAIL, ARROW
    return GraphStructure.from_numpy(out, kind="dag")


def target_truth(truth: GraphStructure, target: Target) -> GraphStructure:
    """Return what an estimate scored as ``target`` is compared with, as in the published summary.

    A CPDAG, or the CPDAG's edges at one variable, is scored against the truth's CPDAG, a DAG
    against the DAG, a PAG, or the PAG's edges at one variable, against the PAG of the observed
    variables, a ``projection`` estimate against :func:`projection`, and a ``direct`` one
    against :func:`direct`.
    """
    if target == "direct":
        return direct(truth)
    if target in ("pag", "target_pag"):
        return marginal(truth, "pag", max_nodes=truth.n_nodes)
    if target == "projection":
        return projection(truth)
    if target in ("cpdag", "target_cpdag"):
        return metrics.to_cpdag(truth)
    return truth


def shd(estimate: object, truth: GraphStructure, target: Target) -> int:
    """Return the SHD of ``estimate`` against ``target_truth``; PAG-like targets count endpoints,
    ``clusters`` the latents missed, ``parents`` the errors in the last variable's parents,
    ``target_cpdag`` and ``target_pag`` the missing, extra, and mismarked edges at the last
    variable, and ``direct`` the directed edges in one graph and not the other, a reversed edge
    twice."""
    if target == "direct":
        return len(directed(estimate) ^ directed(truth))
    if target == "clusters":
        return latents_missed(estimate, truth)
    if target == "parents":
        last = truth.n_nodes - 1
        return set_errors(parents_of(estimate, last), parents_of(truth, last))
    if target in ("target_cpdag", "target_pag"):
        return int(metrics.target_edge_scores(estimate, truth, truth.n_nodes - 1)["shd"])
    if target == "cpdag":
        estimate = metrics.to_cpdag(estimate)
    return metrics.shd(estimate, truth, endpoint_aware=target in ("pag", "projection", "index_pag"))


def set_errors(estimate: set[int], truth: set[int]) -> int:
    """Return the members of ``estimate`` not in ``truth`` plus those of ``truth`` it misses.

    It scores a method that estimates a set of variables, such as one variable's parents, as SHD
    scores a graph: the empty set, the floor, makes ``len(truth)`` errors.
    """
    return len(estimate ^ truth)


def latents_missed(estimate: Any, truth: GraphStructure) -> int:
    """Return the true latents whose indicators ``estimate`` does not return as one cluster, the
    published summary's error count for GIN. The empty graph misses every latent."""
    estimate = getattr(estimate, "structure", estimate)
    found = scoring.measurement_scores(estimate, truth)["measurement_clusters_found"]
    latents = int(np.count_nonzero(np.asarray(truth.node_types) == LATENT))
    return latents - round(found * latents)


def empty_graph(n_nodes: int, target: Target) -> GraphStructure:
    kind = {
        "projection": "pag",
        "index_pag": "pag",
        "target_cpdag": "cpdag",
        "target_pag": "pag",
    }.get(target, target)
    return GraphStructure.from_numpy(np.zeros((n_nodes, n_nodes), dtype=np.int8), kind=kind)


def series_error(estimate: Any, truth: Any, target: Target) -> int:
    """Return the errors of a time-series ``estimate`` in its published summary's unit.

    ``lagged``: the lag-resolved SHD over lags 1..L. ``window``: the endpoint SHD over the window,
    against the true PAG of the observed series when some are unobserved. ``window_edges``: the
    edge SHD over the window of an estimate whose lag 0 is a DAG. ``cross_links``: the
    missing and extra cross-links. ``lagged_edges``: the missing and extra lagged edges.
    """
    if target == "lagged":
        return int(scoring.temporal_score_columns(estimate, truth)["temporal_shd"])
    if target == "window":
        return int(scoring.window_scores(estimate, truth)["endpoint_shd"])
    if target == "window_edges":
        return int(scoring.window_scores(estimate, truth)["shd"])
    if target == "cross_links":
        s = scoring.cross_link_scores(estimate, truth)
        return int(s["cross_n_est"] + s["cross_n_true"] - 2 * s["cross_tp"])
    return int((np.asarray(estimate) ^ np.asarray(truth)).sum())


def target_errors(found: list[list[int]], true: list[list[int]]) -> int:
    """Return the false plus the missed members of each set in ``found`` against its own in
    ``true`` (:func:`set_errors`), over the sets: the target error of the published summary."""
    return sum(set_errors(set(f), set(t)) for f, t in zip(found, true, strict=True))


def empty_estimate(draw: Draw, target: Target) -> Any:
    """The empty graph of ``draw`` in the form ``target`` scores; for ``targets``, the given targets
    alone."""
    truth = draw.truth
    if target == "targets":
        return unknown_target_unstack(draw.data)[2]
    if target == "lagged":
        return temporal_from_links(np.zeros_like(links_from_temporal(truth)))
    if target == "window":
        n = truth.n_nodes - truth.latents
        return WindowGraph(np.zeros((truth.tau_max + 1, n, n), np.int8), lag0="cpdag")
    if target == "window_edges":
        return WindowGraph(np.zeros_like(truth.marks), lag0="dag")
    if target == "cross_links":
        return CoefficientStack(np.zeros_like(truth.stack), kind=truth.kind)
    if target == "lagged_edges":
        return np.zeros_like(truth)
    if target == "essential":  # GIES's and GnIES's data hold the targets or environments too
        return empty_graph(truth.n_nodes, "cpdag")
    if target == "parents":  # the data hold each row's environment beside the variables
        return empty_graph(truth.n_nodes, "dag")
    if target == "clusters":
        return empty_graph(draw.data.shape[1], "dag")
    if target == "direct":
        return empty_graph(draw.data.shape[1], "dag")
    return empty_graph(draw.data.shape[1], target)


