"""Check Andrey's supported methods against data with a known graph before a release.

Each supported method runs on the datasets its assumptions fit: the published benchmark regimes,
generated by ``andrey.data`` at two sizes, cause-effect pairs for the pairwise direction tests, a
linear SCM on the ASIA network, the measured Sachs protein-signaling data, the published regimes
of interventional, multi-domain, multi-group, latent-measurement, and time-series data, drawn and
scored by the benchmark harness, and environments for a method that names one variable's parents.
PC runs with each supported nonlinear conditional-independence test on the published nonlinear
regimes. On each dataset, the median SHD over the draws must be below the empty graph's and within
the tolerance of its recorded baseline; a method that estimates a set of variables, such as one
variable's parents, counts its false and missed members instead (:func:`set_errors`), and one that
answers the edges at a single variable counts the errors at that variable alone.
``quality_baselines.json`` holds the baselines and, in one block, every tolerance with the reason
for its size. Before any fit, the gate runs :mod:`qa.reference_parity` over the published
benchmark summaries as a soft gate: it prints the rows where Andrey makes more errors than the
reference package, and does not fail on them. ``python -m qa.reference_parity`` is the offline
check that exits 1 on such a row, and the release checklist reviews it.

    uv run python -m qa.quality_gate                  # exit 1 if a baseline check fails
    uv run python -m qa.quality_gate PC FCI KCI
    uv run python -m qa.quality_gate --jobs 4         # fit four cells at a time
    uv run python -m qa.quality_gate --capture        # re-measure the baselines; review the diff
"""

