def jpcmciplus_fit(x: np.ndarray) -> Any:
    """``andrey.jpcmciplus`` with both dummies, ``tau_max=2``, and alpha 0.05, the benchmark's
    claimed setting: the window graph of the system variables, as the benchmark driver scores it."""
    params = {**JPCMCIPLUS.params(), "tau_max": 2, "alpha": 0.05, **context_columns(x)}
    marks = np.asarray(JPCMCIPLUS.fit(x, params))
    n = CONTEXT_SYSTEM
    return WindowGraph(marks[:, :n, :n], lag0="cpdag")


def _adapted(adapter: Any) -> Callable[[Any], Any]:
    """The benchmark adapter's fit with the published settings, as the harness scores it."""
    return lambda x: adapter.to_structure(adapter.fit(x, adapter.params()))


def _granger(x: np.ndarray) -> np.ndarray:
    """The lagged edges of ``andrey.granger`` with the published settings, as ``(lag, cause,
    effect)``."""
    out = andrey.granger(x, tau_max=GRANGER_LAGS)
    return np.stack([np.asarray(w) != 0 for w in out.structure.lag_weights])


def ut_igsp_fit(x: np.ndarray) -> Any:
    """``andrey.ut_igsp`` on a stacked draw (:func:`unknown_target_stack`), as the benchmark driver
    calls it: each setting with given targets maps to them, and the others are left unknown."""
    samples, env, given = unknown_target_unstack(x)
    known = {k: targets for k, targets in enumerate(given, start=1) if targets}
    return andrey.ut_igsp(samples, env, targets={0: [], **known})


