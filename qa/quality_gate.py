"""Check Andrey's supported methods against data with a known graph before a release.

Each supported method runs on the datasets its assumptions fit: the published benchmark regimes,
generated by ``andrey.data`` at two sizes, cause-effect pairs for the pairwise direction tests, a
linear SCM on the ASIA network, the measured Sachs protein-signaling data, and the published
regimes of interventional, multi-domain, multi-group, latent-measurement, and time-series data,
drawn and scored by the benchmark harness. On each dataset, the method's
median SHD over the draws must be below the empty graph's and within the tolerance of its recorded
baseline. ``quality_baselines.json`` holds the baselines and, in one block, every tolerance with
the reason for its size. Before any fit, the gate runs :mod:`qa.reference_parity` over the
published benchmark summaries.

    uv run python -m qa.quality_gate                  # exit 1 if any check fails
    uv run python -m qa.quality_gate PC FCI
    uv run python -m qa.quality_gate --capture        # re-measure the baselines; review the diff
"""

