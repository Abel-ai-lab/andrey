@dataclass
class CellResult:
    """One method on one dataset: the SHD of each draw and of the empty graph, and both checks."""

    method: str
    dataset: str
    shd: list[int]
    empty_shd: list[int]
    baseline: float | None
    tolerance: float | None
    seconds: float = 0.0

    @property
    def median(self) -> float:
        return float(statistics.median(self.shd))

    @property
    def empty_median(self) -> float:
        return float(statistics.median(self.empty_shd))

    @property
    def failures(self) -> list[str]:
        out = []
        if not self.median < self.empty_median:
            out.append(
                f"median SHD {self.median:g} is not below the empty graph's {self.empty_median:g}"
            )
        if self.baseline is None or self.tolerance is None:
            out.append("no recorded baseline")
        elif abs(self.median - self.baseline) > self.tolerance:
            gap = self.median - self.baseline
            out.append(
                f"median SHD {self.median:g} is {abs(gap):g} {'above' if gap > 0 else 'below'} "
                f"the baseline {self.baseline:g} (tolerance {self.tolerance:g})"
                + ("" if gap > 0 else "; recapture if the change is intended")
            )
        return out

    @property
    def passed(self) -> bool:
        return not self.failures

    def describe(self, verdict: str | None = None) -> str:
        baseline = (
            "none"
            if self.baseline is None or self.tolerance is None
            else f"{self.baseline:g} ± {self.tolerance:g}"
        )
        verdict = verdict or ("PASS" if self.passed else "FAIL")
        return (
            f"[{verdict}] {self.method:12s} {self.dataset:20s} "
            f"SHD {self.median:5g}  empty {self.empty_median:5g}  baseline {baseline:9s} "
            f"{self.seconds:6.1f} s"
        )


def recorded() -> dict:
    """Return the ``supported`` block of ``quality_baselines.json``."""
    return json.loads(BASELINES.read_text())["supported"]


def evaluate(method: str, dataset: str, fit: Callable[[Draw], object] | None = None) -> CellResult:
    """Run ``method`` on each draw of ``dataset`` and check the result.

    ``fit`` replaces the method's own fit, so a test can feed the gate a chosen result. The numpy
    backend, one worker, and one BLAS thread keep the result independent of the host's devices and
    core count.
    """
    spec = CHECKS[method]
    run = fit or (lambda draw: spec.fit(draw.data))
    shds, empties = [], []
    start = time.perf_counter()
    with andrey.config(backend="numpy", n_jobs=1), threadpool_limits(limits=1):
        for draw in draws(dataset):
            empty = empty_estimate(draw, spec.target)
            if spec.target in SERIES_TARGETS:
                shds.append(series_error(run(draw), draw.truth, spec.target))
                empties.append(series_error(empty, draw.truth, spec.target))
                continue
            truth = target_truth(draw.truth, spec.target)
            shds.append(shd(run(draw), truth, spec.target))
            empties.append(shd(empty, truth, spec.target))
    ledger = recorded()
    cell = ledger["baselines"].get(method, {}).get(dataset, {})
    return CellResult(
        method=method,
        dataset=dataset,
        shd=shds,
        empty_shd=empties,
        baseline=cell.get("median_shd"),
        tolerance=ledger["tolerances"].get(method, {}).get("median_shd"),
        seconds=time.perf_counter() - start,
    )


def cells(methods: list[str] | None = None) -> list[tuple[str, str]]:
    """Return the ``(method, dataset)`` pairs of ``methods`` (default: every check)."""
    return [(m, ds) for m in methods or list(CHECKS) for ds in CHECKS[m].datasets]


#: The cells that take over 10 seconds on a CI runner, slowest first. With several jobs they start
#: first, so no worker is left fitting one long cell after the others have finished.
SLOWEST_FIRST: tuple[tuple[str, str], ...] = (
    ("CMIknn", "anm_er_d5"),
    ("CALM", "linear_gauss_er_d10"),
    ("BottomUpParceLiNGAM", "latent_lingam_er_d15"),
    ("CMIknn", "nonmonotone_er_d5"),
    ("CALM", "asia_gauss"),
    ("VARMA-LiNGAM", "varma_lingam_paper_d5_n300"),
    ("KCI", "anm_er_d10"),
    ("KCI", "nonmonotone_er_d10"),
    ("BottomUpParceLiNGAM", "latent_lingam_er_d10"),
    ("RCD", "latent_lingam_er_d15"),
    ("DirectLiNGAM", "lingam_sf_d50"),
    ("RCD", "latent_lingam_er_d10"),
    ("ANM", "anm_pair_n1000"),
    ("GIN", "latent_measurement_d12"),
    ("GPDC", "anm_er_d5"),
    ("VARMA-LiNGAM", "varma_lingam_paper_d3_n300"),
    ("GPDC", "nonmonotone_er_d5"),
    ("ExactSearch", "linear_gauss_er_d15"),
)


def start_order(todo: list[tuple[str, str]]) -> list[int]:
    """Return the indices of ``todo`` in the order its cells start: :data:`SLOWEST_FIRST`, then the
    rest in their own order."""
    rank = {cell: i for i, cell in enumerate(SLOWEST_FIRST)}
    return sorted(range(len(todo)), key=lambda i: (rank.get(todo[i], len(rank)), i))


def evaluate_indexed(task: tuple[int, str, str]) -> tuple[int, CellResult]:
    index, method, dataset = task
    return index, evaluate(method, dataset)


def run_cells(todo: list[tuple[str, str]], jobs: int = 1) -> Iterator[CellResult]:
    """Yield the result of each ``(method, dataset)`` cell of ``todo``, in order.

    With ``jobs`` above 1, worker processes fit the cells, longest first (:func:`start_order`), and
    a result is yielded once it and every cell before it have finished. Each worker runs
    :func:`evaluate`, so a cell's fit has the same settings as with one job. The workers start with
    ``spawn``: ``forkserver`` needs a socket in ``TMPDIR``, which some cluster file systems reject.
    """
    if jobs == 1 or len(todo) < 2:
        for method, dataset in todo:
            yield evaluate(method, dataset)
        return
    if any(dataset == "sachs" for _, dataset in todo):
        draws("sachs")  # download the rows once, before the workers read the cache
    tasks = [(i, *todo[i]) for i in start_order(todo)]
    done: dict[int, CellResult] = {}
    next_index = 0
    with multiprocessing.get_context("spawn").Pool(min(jobs, len(todo))) as pool:
        for index, result in pool.imap_unordered(evaluate_indexed, tasks, chunksize=1):
            done[index] = result
            while next_index in done:
                yield done.pop(next_index)
                next_index += 1


def capture(results: list[CellResult]) -> None:
    """Replace the baselines of each method in ``results``; keep every other recorded value."""
    everything = json.loads(BASELINES.read_text())
    baselines = everything["supported"]["baselines"]
    for method in {r.method for r in results}:
        baselines[method] = {}
    for r in results:
        baselines[r.method][r.dataset] = {
            "median_shd": r.median,
            "empty_median_shd": r.empty_median,
            "shd": r.shd,
        }
    everything["supported"]["baselines"] = {m: baselines[m] for m in CHECKS if m in baselines}
    BASELINES.write_text(_dumps(everything) + "\n")


def _dumps(obj: object, depth: int = 0) -> str:
    """JSON with one line per leaf object, so a recapture diff shows one line per changed cell."""
    if not isinstance(obj, dict) or not any(isinstance(v, dict) for v in obj.values()):
        return json.dumps(obj, ensure_ascii=False)
    pad = "  " * (depth + 1)
    items = [f"{pad}{json.dumps(k)}: {_dumps(v, depth + 1)}" for k, v in obj.items()]
    return "{\n" + ",\n".join(items) + "\n" + "  " * depth + "}"


